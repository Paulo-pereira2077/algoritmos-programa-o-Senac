public class Opcoes {

    private String codCurso;
    private String codBolsa;

    public Opcoes(String codCurso, String codBolsa) {
        this.codCurso = codCurso;
        this.codBolsa = codBolsa;
    }

    public String getCodCurso() {
        return codCurso;
    }

    public String getCodBolsa() {
        return codBolsa;
    }
}
